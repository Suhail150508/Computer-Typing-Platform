<?php

namespace App\Support;

/**
 * অনুশীলন ট্রেনারের কীবোর্ড ডেটা।
 * বিজয় ম্যাপ: [কী, সাধারণ (Shift ছাড়া), Shift সহ] — ডেটা বদলাতে হলে শুধু এই ফাইল এডিট করুন।
 * অভ্র (ফোনেটিক) এ কীবোর্ডে ইংরেজি অক্ষর থাকে; কোন অক্ষরে কোন বাংলা আসে তা পাঠের সিকোয়েন্সে (Lessons) দেওয়া।
 */
class KeyLayouts
{
    /** @return array<int, array<int, array{0:string,1:string,2:string}>> */
    public static function bijoy(): array
    {
        return [
            [['1', '১', '!'], ['2', '২', '@'], ['3', '৩', '#'], ['4', '৪', '৳'], ['5', '৫', '%'], ['6', '৬', '^'], ['7', '৭', 'ঁ'], ['8', '৮', '*'], ['9', '৯', '('], ['0', '০', ')'], ['\\', 'ৎ', 'ঃ']],
            [['q', 'ঙ', 'ং'], ['w', 'য', 'য়'], ['e', 'ড', 'ঢ'], ['r', 'প', 'ফ'], ['t', 'ট', 'ঠ'], ['y', 'চ', 'ছ'], ['u', 'জ', 'ঝ'], ['i', 'হ', 'ঞ'], ['o', 'গ', 'ঘ'], ['p', 'ড়', 'ঢ়']],
            [['a', 'ঋ', 'ৃ'], ['s', 'ু', 'ূ'], ['d', 'ি', 'ী'], ['f', 'া', 'অ'], ['g', '্', '।'], ['h', 'ব', 'ভ'], ['j', 'ক', 'খ'], ['k', 'ত', 'থ'], ['l', 'দ', 'ধ'], [';', ';', ':']],
            [['z', '্র', '্য'], ['x', 'ও', 'ৗ'], ['c', 'ে', 'ৈ'], ['v', 'র', 'ল'], ['b', 'ন', 'ণ'], ['n', 'স', 'ষ'], ['m', 'ম', 'শ'], [',', ',', '<'], ['.', '.', '>'], ['/', '/', '?']],
        ];
    }

    /** অভ্র ট্রেনারের কীবোর্ড (শুধু ইংরেজি অক্ষর) */
    public static function plain(): array
    {
        $rows = ['1234567890', 'qwertyuiop', 'asdfghjkl;', 'zxcvbnm,./'];

        return array_map(fn ($r) => array_map(fn ($c) => [$c, strtoupper($c) === $c ? $c : strtoupper($c), ''], str_split($r)), $rows);
    }

    /** কোন আঙুল (কলাম অনুযায়ী) */
    public const TYPES = ['pinky', 'ring', 'middle', 'index', 'index', 'index', 'index', 'middle', 'ring', 'pinky', 'pinky'];

    /** @return array<string, string> কী → আঙুলের নাম */
    public static function fingers(): array
    {
        $left = ['কনিষ্ঠা', 'অনামিকা', 'মধ্যমা', 'তর্জনী', 'তর্জনী'];
        $right = ['তর্জনী', 'তর্জনী', 'মধ্যমা', 'অনামিকা', 'কনিষ্ঠা', 'কনিষ্ঠা'];
        $map = [];
        foreach (['1234567890\\', 'qwertyuiop', 'asdfghjkl;', 'zxcvbnm,./'] as $row) {
            foreach (str_split($row) as $i => $c) {
                $map[$c] = $i < 5 ? 'বাম '.$left[$i] : 'ডান '.$right[$i - 5];
            }
        }
        $map[' '] = 'যেকোনো বুড়ো আঙুল';

        return $map;
    }
}
